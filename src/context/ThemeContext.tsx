interface ThemeContextType {
  currentTheme: ThemeDefinition;
  setThemeId: (id: ThemeId) => void;
  themes: ThemeDefinition[];
  fontStyle: FontStyle;
  setFontStyle: (font: FontStyle) => void;
  fontSize: FontSize;
  setFontSize: (size: FontSize) => void;
  fontStyles: FontStyleOption[];
  fontSizes: FontSizeOption[];
  isPickerOpen: boolean;
  setIsPickerOpen: (open: boolean) => void;
}

const ThemeContext = createContext<ThemeContextType | undefined>(undefined);

export const ThemeProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [themeId, setThemeIdState] = useState<ThemeId>(() => {
    const saved = localStorage.getItem('devbloom_theme_id') as ThemeId;
    if (saved && THEMES.some((t) => t.id === saved)) {
      return saved;
    }
    return 'dark-pink';
  });

  const [fontStyle, setFontStyleState] = useState<FontStyle>(() => {
    const saved = localStorage.getItem('devbloom_font_style') as FontStyle;
    return saved && FONT_STYLES.some((f) => f.id === saved) ? saved : 'sans';
  });

  const [fontSize, setFontSizeState] = useState<FontSize>(() => {
    const saved = localStorage.getItem('devbloom_font_size') as FontSize;
    return saved && FONT_SIZES.some((f) => f.id === saved) ? saved : 'md';
  });

  const [isPickerOpen, setIsPickerOpen] = useState(false);

  const currentTheme = THEMES.find((t) => t.id === themeId) || THEMES[0];

  useEffect(() => {
    localStorage.setItem('devbloom_theme_id', themeId);
    localStorage.setItem('devbloom_font_style', fontStyle);
    localStorage.setItem('devbloom_font_size', fontSize);

    // Apply CSS variables & font settings to root element
    const root = document.documentElement;
    Object.entries(currentTheme.vars).forEach(([key, value]) => {
      root.style.setProperty(key, value);
    });

    const selectedFont = FONT_STYLES.find((f) => f.id === fontStyle) || FONT_STYLES[0];
    const selectedSize = FONT_SIZES.find((s) => s.id === fontSize) || FONT_SIZES[1];

    root.style.setProperty('--app-font-family', selectedFont.fontFamily);
    root.style.setProperty('--app-font-size-base', selectedSize.scale);
    root.style.fontFamily = selectedFont.fontFamily;
    root.style.fontSize = selectedSize.scale;
  }, [themeId, currentTheme, fontStyle, fontSize]);

  const setThemeId = (id: ThemeId) => {
    setThemeIdState(id);
  };

  const setFontStyle = (font: FontStyle) => {
    setFontStyleState(font);
  };

  const setFontSize = (size: FontSize) => {
    setFontSizeState(size);
  };

  return (
    <ThemeContext.Provider
      value={{
        currentTheme,
        setThemeId,
        themes: THEMES,
        fontStyle,
        setFontStyle,
        fontSize,
        setFontSize,
        fontStyles: FONT_STYLES,
        fontSizes: FONT_SIZES,
        isPickerOpen,
        setIsPickerOpen,
      }}
    >
      {children}
    </ThemeContext.Provider>
  );
};

export const useTheme = () => {
  const context = useContext(ThemeContext);
  if (!context) {
    throw new Error('useTheme must be used within a ThemeProvider');
  }
  return context;
};
